export function translateEnglish(value) {
  if (!value || typeof value !== 'string') return value
  return [...englishReplacements]
    .sort(([left], [right]) => right.length - left.length)
    .reduce((text, [from, to]) => text.replaceAll(from, to), value)
}

export const useLocaleStore = defineStore('locale', () => {
  const locale = ref(localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'zh')
  const t = (key) => messages[locale.value][key] || messages.zh[key] || key
  const setLocale = (value) => {
    const next = value === 'en' ? 'en' : 'zh'
    if (next === locale.value) return
    locale.value = next
    localStorage.setItem(STORAGE_KEY, locale.value)
    window.location.reload()
  }
  return { locale, t, setLocale }
})
